package com.example.pdfmaker

enum class Category(val label: String) {
    BUSINESS("Business & Finance"), WORK("Work & HR"), LOGISTICS("Logistics & Inventory"),
    HOME("Personal & Home"), HEALTH("Health & Fitness"), EDU("Education"),
    EVENTS("Events & Community"), LEGAL("Legal & Property")
}
enum class DocLayout { CUSTOM, LETTER, SHEET, CHECKBOX, CARD, LABEL }
data class FieldDef(val key: String, val label: String,
                    val multi: Boolean = false, val num: Boolean = false, val prefill: String? = null)
data class TableDef(val title: String, val c1: String, val c2: String, val c3: String,
                    val num2: Boolean = true, val num3: Boolean = true, val blankRows: Int = 0)
data class DocSpec(val id: String, val icon: String, val label: String, val desc: String,
    val cat: Category, val layout: DocLayout, val fields: List<FieldDef> = emptyList(),
    val table: TableDef? = null, val totals: Boolean = false, val signature: Boolean = false,
    val totalMoney: Boolean = true, val totalCol: Int = 3,
    val landscape: Boolean = false, val footer: Boolean = true)

private val BUS = Category.BUSINESS; private val WRK = Category.WORK
private val LOG = Category.LOGISTICS; private val HOM = Category.HOME
private val HLT = Category.HEALTH; private val EDU = Category.EDU
private val EVT = Category.EVENTS; private val LGL = Category.LEGAL

private fun f(key: String, label: String, num: Boolean = false, prefill: String? = null) =
    FieldDef(key, label, false, num, prefill)
private fun fm(key: String, label: String, prefill: String? = null) =
    FieldDef(key, label, true, false, prefill)
private fun tbl(title: String, c1: String, c2: String, c3: String,
                num2: Boolean = true, num3: Boolean = true, blankRows: Int = 0) =
    TableDef(title, c1, c2, c3, num2, num3, blankRows)

private fun spec(id: String, icon: String, label: String, desc: String, cat: Category,
                 layout: DocLayout, vararg fields: FieldDef, table: TableDef? = null,
                 totals: Boolean = false, signature: Boolean = false, totalMoney: Boolean = true,
                 totalCol: Int = 3, landscape: Boolean = false, footer: Boolean = true) =
    DocSpec(id, icon, label, desc, cat, layout, fields.toList(), table,
        totals, signature, totalMoney, totalCol, landscape, footer)

